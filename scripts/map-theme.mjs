// npm run map-theme: the colour grade that keeps the whole 3D map in the app's lantern-night palette.
// Mapbox Standard lets a style recolour everything it draws (land, water, airports, the detailed 3D
// landmark models, labels) through a 32×32×32 lookup table; the grade is applied after the time-of-day
// light, so day stays lighter than night. It compresses brightness into the night range, softens the
// whites, tints toward indigo and keeps half of each colour's own hue (parks green, water blue,
// motorways warm). Writes src/app/map-theme.ts.
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';

const N = 32, W = N * N;
const lum = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;
const TINT = [0.9, 0.94, 1.22]; // indigo

function grade(r, g, b) {
  const l = lum(r, g, b);
  let t = 0.045 + 0.62 * Math.pow(l, 1.12);
  if (t > 0.42) t = 0.42 + (t - 0.42) * 0.4; // whites (terminal buildings, landmarks) sit back
  return [r, g, b].map((c, k) => t * TINT[k] + (c - l) * 0.5);
}

// The table as Mapbox reads it: 1024×32, one 32×32 tile per blue level, red across, green down.
const buf = Buffer.alloc(W * N * 3);
for (let bl = 0; bl < N; bl++) for (let gr = 0; gr < N; gr++) for (let re = 0; re < N; re++) {
  const o = grade(re / (N - 1), gr / (N - 1), bl / (N - 1));
  const i = (gr * W + bl * N + re) * 3;
  for (let k = 0; k < 3; k++) buf[i + k] = Math.round(Math.min(1, Math.max(0, o[k])) * 255);
}
const png = await sharp(buf, { raw: { width: W, height: N, channels: 3 } }).png({ compressionLevel: 9 }).toBuffer();
writeFileSync(new URL('../src/app/map-theme.ts', import.meta.url), `// Generated by scripts/map-theme.mjs (npm run map-theme): the lantern-night colour grade for the map.\nexport const MAP_THEME = '${png.toString('base64')}';\n`);
console.log(`map-theme.ts: ${(png.length / 1024).toFixed(1)} KB`);
